-- Submission with a Storage object: begin (limit and duplicates), upload in Core, then submit.
-- ---------------------------------------------------------------------------------------------

-- The same field rules as 0025's submit routine, shared by the Storage path. Returns the first
-- invalid field, or NULL.
CREATE FUNCTION private.membership_invalid_field(
  p_full_name text, p_email text, p_university_id text, p_academic_year integer,
  p_discipline text, p_interests text[], p_consent_version text, p_status_token_hash text
) RETURNS text LANGUAGE plpgsql IMMUTABLE SET search_path = public, pg_temp AS $$
DECLARE
  v_name text := btrim(coalesce(p_full_name, ''));
  v_email text := lower(btrim(coalesce(p_email, '')));
  v_interests text[] := coalesce(p_interests, '{}');
BEGIN
  IF char_length(v_name) NOT BETWEEN 1 AND 200 OR v_name ~ '[[:cntrl:]]' THEN RETURN 'fullName'; END IF;
  IF char_length(v_email) > 254 OR v_email !~ '^[^[:space:]@]+@([a-z0-9-]+\.)*squ\.edu\.om$' THEN
    RETURN 'email';
  END IF;
  IF btrim(coalesce(p_university_id, '')) !~ '^[0-9]{6,10}$' THEN RETURN 'universityId'; END IF;
  IF p_academic_year IS NULL OR p_academic_year NOT BETWEEN 1 AND 5 THEN RETURN 'academicYear'; END IF;
  IF p_discipline IS NULL OR p_discipline NOT IN
      ('mechanical', 'electrical', 'civil', 'petroleum', 'chemical', 'mechatronics', 'industrial') THEN
    RETURN 'discipline';
  END IF;
  IF cardinality(v_interests) > 4 OR array_position(v_interests, NULL) IS NOT NULL
      OR NOT (v_interests <@ ARRAY['cad', 'simulation', 'embedded', 'robotics', 'structures',
        'process', 'data', 'programming', 'power', 'reservoir', 'quality', 'management',
        'sustainability', 'hse'])
      OR (SELECT count(DISTINCT x) FROM unnest(v_interests) x) <> cardinality(v_interests) THEN
    RETURN 'interests';
  END IF;
  IF p_consent_version IS NULL OR p_consent_version NOT IN ('2026-10-v1') THEN RETURN 'consent'; END IF;
  IF p_status_token_hash IS NULL OR p_status_token_hash !~ '^[0-9a-f]{64}$' THEN RETURN 'statusToken'; END IF;
  RETURN NULL;
END;
$$;

-- Step 1, before anything is uploaded: records the attempt, applies the per-address limit (the
-- same five an hour as 0025) and refuses known duplicates, so a refused applicant uploads nothing.
CREATE FUNCTION private.begin_membership_submission(p_email text, p_university_id text, p_ip inet)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
  v_email text := lower(btrim(coalesce(p_email, '')));
  v_university_id text := btrim(coalesce(p_university_id, ''));
  v_recent integer;
BEGIN
  IF p_ip IS NULL THEN RETURN jsonb_build_object('code', 'INVALID_IP'); END IF;
  IF char_length(v_email) > 254 OR v_email !~ '^[^[:space:]@]+@([a-z0-9-]+\.)*squ\.edu\.om$' THEN
    RETURN jsonb_build_object('code', 'VALIDATION_ERROR', 'field', 'email');
  END IF;
  IF v_university_id !~ '^[0-9]{6,10}$' THEN
    RETURN jsonb_build_object('code', 'VALIDATION_ERROR', 'field', 'universityId');
  END IF;

  DELETE FROM private.membership_submission_attempts WHERE created_at < clock_timestamp() - interval '1 day';
  INSERT INTO private.membership_submission_attempts (ip_address) VALUES (p_ip);
  SELECT count(*) INTO v_recent FROM private.membership_submission_attempts
  WHERE ip_address = p_ip AND created_at > clock_timestamp() - interval '1 hour';
  IF v_recent > 5 THEN RETURN jsonb_build_object('code', 'RATE_LIMITED'); END IF;

  IF EXISTS (SELECT 1 FROM public.members
      WHERE lower(email) = v_email OR university_id = v_university_id) THEN
    RETURN jsonb_build_object('code', 'ALREADY_MEMBER');
  END IF;
  IF EXISTS (SELECT 1 FROM private.membership_applications
      WHERE status IN ('pending_review', 'verified', 'approved')
        AND (email = v_email OR university_id = v_university_id)) THEN
    RETURN jsonb_build_object('code', 'ALREADY_APPLIED');
  END IF;
  RETURN jsonb_build_object('code', 'SUCCESS');
END;
$$;

-- Step 3, after Core stored the object: validates everything again, requires a recent begin from
-- the same address (so the limit cannot be skipped), re-checks duplicates under the unique
-- indexes, and writes the application, the document reference and the audit row together.
CREATE FUNCTION private.submit_stored_membership_application(
  p_full_name text, p_email text, p_university_id text, p_academic_year integer,
  p_discipline text, p_interests text[], p_consent_version text, p_status_token_hash text,
  p_media_type text, p_sha256 text, p_byte_size integer, p_storage_bucket text, p_storage_key text,
  p_ip inet
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
  v_field text;
  v_email text := lower(btrim(coalesce(p_email, '')));
  v_university_id text := btrim(coalesce(p_university_id, ''));
  v_recent integer;
  v_started boolean;
  v_constraint text;
  v_id uuid;
BEGIN
  IF p_ip IS NULL THEN RETURN jsonb_build_object('code', 'INVALID_IP'); END IF;
  v_field := private.membership_invalid_field(p_full_name, p_email, p_university_id,
    p_academic_year, p_discipline, p_interests, p_consent_version, p_status_token_hash);
  IF v_field IS NOT NULL THEN
    RETURN jsonb_build_object('code', 'VALIDATION_ERROR', 'field', v_field);
  END IF;
  IF p_media_type IS NULL OR p_media_type NOT IN ('image/jpeg', 'image/png', 'image/webp', 'application/pdf')
      OR p_byte_size IS NULL OR p_byte_size NOT BETWEEN 1 AND 4194304
      OR p_sha256 IS NULL OR p_sha256 !~ '^[0-9a-f]{64}$'
      OR p_storage_bucket IS NULL OR p_storage_bucket !~ '^[A-Za-z0-9][A-Za-z0-9._-]{0,62}$'
      OR p_storage_key IS NULL OR p_storage_key !~
        '^membership-id-cards/[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}\.(jpg|png|webp|pdf)$'
      -- Parenthesised: PL/pgSQL would otherwise end the IF condition at the CASE's first THEN.
      OR p_storage_key NOT LIKE ('%.' || (CASE p_media_type
        WHEN 'image/jpeg' THEN 'jpg' WHEN 'image/png' THEN 'png'
        WHEN 'image/webp' THEN 'webp' WHEN 'application/pdf' THEN 'pdf' END)) THEN
    RETURN jsonb_build_object('code', 'VALIDATION_ERROR', 'field', 'idDocument');
  END IF;

  SELECT count(*), bool_or(created_at > clock_timestamp() - interval '10 minutes')
  INTO v_recent, v_started
  FROM private.membership_submission_attempts
  WHERE ip_address = p_ip AND created_at > clock_timestamp() - interval '1 hour';
  IF NOT coalesce(v_started, false) THEN RETURN jsonb_build_object('code', 'NOT_STARTED'); END IF;
  IF v_recent > 5 THEN RETURN jsonb_build_object('code', 'RATE_LIMITED'); END IF;

  IF EXISTS (SELECT 1 FROM public.members
      WHERE lower(email) = v_email OR university_id = v_university_id) THEN
    RETURN jsonb_build_object('code', 'ALREADY_MEMBER');
  END IF;
  IF EXISTS (SELECT 1 FROM private.membership_applications
      WHERE status IN ('pending_review', 'verified', 'approved')
        AND (email = v_email OR university_id = v_university_id)) THEN
    RETURN jsonb_build_object('code', 'ALREADY_APPLIED');
  END IF;

  BEGIN
    INSERT INTO private.membership_applications
      (full_name, email, university_id, academic_year, discipline, interests,
       consent_version, status_token_hash)
    VALUES (btrim(p_full_name), v_email, v_university_id, p_academic_year, p_discipline,
       coalesce(p_interests, '{}'), p_consent_version, p_status_token_hash)
    RETURNING id INTO v_id;
    INSERT INTO private.membership_documents
      (application_id, media_type, byte_size, sha256, content, storage_bucket, storage_key)
    VALUES (v_id, p_media_type, p_byte_size, p_sha256, NULL, p_storage_bucket, p_storage_key);
  EXCEPTION WHEN unique_violation THEN
    GET STACKED DIAGNOSTICS v_constraint = CONSTRAINT_NAME;
    -- The object key is random; a clash means the request is not genuine, not a duplicate person.
    IF v_constraint = 'membership_documents_storage_object_unique' THEN
      RETURN jsonb_build_object('code', 'VALIDATION_ERROR', 'field', 'idDocument');
    END IF;
    RETURN jsonb_build_object('code', 'ALREADY_APPLIED');
  END;

  INSERT INTO private.uc02_audit (committee_id, actor_kind, action, changes)
  VALUES (NULL, 'anonymous', 'membership.submitted', jsonb_build_object('applicationId', v_id));
  RETURN jsonb_build_object('code', 'SUCCESS', 'applicationId', v_id);
END;
$$;

-- ---------------------------------------------------------------------------------------------
-- Deletion queue: abandoned uploads in, claimed batches out, completion recorded.
-- ---------------------------------------------------------------------------------------------

-- For an object Core stored (or may have stored) that no application references: a failed or
-- timed-out upload, or one whose application was refused. A referenced object is never queued.
CREATE FUNCTION private.queue_abandoned_membership_upload(p_storage_bucket text, p_storage_key text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
BEGIN
  IF p_storage_bucket IS NULL OR p_storage_bucket !~ '^[A-Za-z0-9][A-Za-z0-9._-]{0,62}$'
      OR p_storage_key IS NULL OR p_storage_key !~
        '^membership-id-cards/[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}\.(jpg|png|webp|pdf)$' THEN
    RETURN jsonb_build_object('code', 'VALIDATION_ERROR');
  END IF;
  IF EXISTS (SELECT 1 FROM private.membership_documents d
      WHERE d.storage_bucket = p_storage_bucket AND d.storage_key = p_storage_key) THEN
    RETURN jsonb_build_object('code', 'REFERENCED');
  END IF;
  INSERT INTO private.membership_storage_deletions (storage_bucket, storage_key, reason)
  VALUES (p_storage_bucket, p_storage_key, 'upload_abandoned')
  ON CONFLICT (storage_bucket, storage_key) DO NOTHING;
  RETURN jsonb_build_object('code', 'SUCCESS');
END;
$$;

-- Hands out up to p_limit pending deletions, skipping any object a document references and any
-- tried in the last minute (so concurrent workers do not repeat each other's work).
CREATE FUNCTION private.claim_membership_storage_deletions(p_limit integer)
RETURNS TABLE (deletion_id uuid, bucket text, object_key text)
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
BEGIN
  IF p_limit IS NULL OR p_limit NOT BETWEEN 1 AND 50 THEN RETURN; END IF;
  RETURN QUERY
  WITH picked AS (
    SELECT q.id FROM private.membership_storage_deletions q
    WHERE q.completed_at IS NULL
      AND (q.last_attempt_at IS NULL OR q.last_attempt_at < clock_timestamp() - interval '1 minute')
      AND NOT EXISTS (SELECT 1 FROM private.membership_documents d
        WHERE d.storage_bucket = q.storage_bucket AND d.storage_key = q.storage_key)
    ORDER BY q.requested_at
    LIMIT p_limit
    FOR UPDATE SKIP LOCKED
  )
  UPDATE private.membership_storage_deletions q
  SET attempts = q.attempts + 1, last_attempt_at = clock_timestamp()
  FROM picked WHERE q.id = picked.id
  RETURNING q.id, q.storage_bucket, q.storage_key;
END;
$$;

CREATE FUNCTION private.complete_membership_storage_deletion(p_deletion_id uuid)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
BEGIN
  UPDATE private.membership_storage_deletions SET completed_at = clock_timestamp()
  WHERE id = p_deletion_id AND completed_at IS NULL;
  RETURN jsonb_build_object('code', CASE WHEN FOUND THEN 'SUCCESS' ELSE 'NOT_FOUND' END);
END;
$$;

-- ---------------------------------------------------------------------------------------------
-- Reviewer document read: unchanged checks and audit, now also returning the Storage reference.
-- The return type changes, so the function is replaced rather than altered.
-- ---------------------------------------------------------------------------------------------
DROP FUNCTION private.get_membership_document(uuid, uuid);
CREATE FUNCTION private.get_membership_document(p_actor uuid, p_application_id uuid)
RETURNS TABLE (media_type text, byte_size integer, sha256 text, content bytea,
  storage_bucket text, storage_key text)
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE v_kind text := private.membership_reviewer_kind(p_actor, false); v_email text;
BEGIN
  IF v_kind IS NULL OR p_application_id IS NULL THEN RETURN; END IF;
  SELECT a.email INTO v_email FROM private.membership_applications a WHERE a.id = p_application_id;
  IF NOT FOUND OR v_email = private.membership_actor_email(p_actor) THEN RETURN; END IF;
  IF NOT EXISTS (SELECT 1 FROM private.membership_documents d WHERE d.application_id = p_application_id) THEN
    RETURN;
  END IF;
  INSERT INTO private.uc02_audit (committee_id, actor_kind, actor_user_id, action, changes)
  VALUES (NULL, 'authenticated', p_actor, 'membership.document_viewed',
    jsonb_build_object('applicationId', p_application_id));
  RETURN QUERY SELECT d.media_type, d.byte_size, d.sha256, d.content, d.storage_bucket, d.storage_key
  FROM private.membership_documents d WHERE d.application_id = p_application_id;
END;
$$;

-- ---------------------------------------------------------------------------------------------
-- Ownership and execution grants.
-- ---------------------------------------------------------------------------------------------
DO $$
DECLARE v_fn text;
BEGIN
  FOREACH v_fn IN ARRAY ARRAY[
    'private.queue_removed_membership_document()',
    'private.membership_invalid_field(text, text, text, integer, text, text[], text, text)',
    'private.begin_membership_submission(text, text, inet)',
    'private.submit_stored_membership_application(text, text, text, integer, text, text[], text, text, text, text, integer, text, text, inet)',
    'private.queue_abandoned_membership_upload(text, text)',
    'private.claim_membership_storage_deletions(integer)',
    'private.complete_membership_storage_deletion(uuid)',
    'private.get_membership_document(uuid, uuid)'
  ] LOOP
    EXECUTE format('ALTER FUNCTION %s OWNER TO uc02_routine_owner', v_fn);
    EXECUTE format('REVOKE ALL ON FUNCTION %s FROM PUBLIC', v_fn);
  END LOOP;
  FOREACH v_fn IN ARRAY ARRAY[
    'private.begin_membership_submission(text, text, inet)',
    'private.submit_stored_membership_application(text, text, text, integer, text, text[], text, text, text, text, integer, text, text, inet)',
    'private.queue_abandoned_membership_upload(text, text)',
    'private.claim_membership_storage_deletions(integer)',
    'private.complete_membership_storage_deletion(uuid)',
    'private.get_membership_document(uuid, uuid)'
  ] LOOP
    EXECUTE format('GRANT EXECUTE ON FUNCTION %s TO app_runtime', v_fn);
  END LOOP;
END;
$$;

-- The migration proves its own boundary; any failure rolls the whole migration back.
DO $$
DECLARE v_count integer;
BEGIN
  SELECT count(*) INTO v_count FROM information_schema.role_table_grants
  WHERE grantee IN ('app_runtime', 'app_maintenance', 'anon', 'authenticated')
    AND table_schema = 'private' AND table_name LIKE 'membership%';
  IF v_count <> 0 THEN
    RAISE EXCEPTION 'no login or browser role may hold privileges on membership tables, found %', v_count;
  END IF;
  IF NOT (SELECT relrowsecurity AND relforcerowsecurity FROM pg_class
      WHERE oid = 'private.membership_storage_deletions'::regclass) THEN
    RAISE EXCEPTION 'private.membership_storage_deletions must have forced row level security';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_trigger
      WHERE tgname = 'membership_document_removed'
        AND tgrelid = 'private.membership_documents'::regclass AND tgenabled = 'O') THEN
    RAISE EXCEPTION 'the document removal trigger must be enabled';
  END IF;
  IF NOT has_function_privilege('app_runtime', 'private.get_membership_document(uuid, uuid)', 'EXECUTE')
      OR NOT has_function_privilege('app_runtime', 'private.claim_membership_storage_deletions(integer)', 'EXECUTE') THEN
    RAISE EXCEPTION 'app_runtime must be able to execute the document and deletion routines';
  END IF;
  IF has_function_privilege('app_runtime',
        'private.membership_invalid_field(text, text, text, integer, text, text[], text, text)', 'EXECUTE')
      OR has_function_privilege('anon', 'private.begin_membership_submission(text, text, inet)', 'EXECUTE')
      OR has_function_privilege('authenticated', 'private.get_membership_document(uuid, uuid)', 'EXECUTE')
      OR has_function_privilege('authenticated', 'private.claim_membership_storage_deletions(integer)', 'EXECUTE') THEN
    RAISE EXCEPTION 'an internal or browser-facing role can execute a membership routine it must not';
  END IF;
END;
$$;

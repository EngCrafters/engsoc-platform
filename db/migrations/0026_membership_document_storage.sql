-- UC-01 membership ID cards in private Supabase Storage (ADR 0018).
--
-- Forward-only and additive on top of 0025, which stays unchanged. A document row now holds either
-- the bytes in PostgreSQL (0025, still used until Storage is configured) or a reference to a
-- private Storage object, never both. Core uploads the object with server-only S3 credentials
-- before the application row exists; the database records only the bucket, a random key, the type,
-- the size and the SHA-256. Removing a document row (at approval or rejection) queues its object
-- for deletion in the same transaction, and Core deletes queued objects and records completion.
-- Nothing in the database talks to Storage, and no browser or login role can read any of this.

-- ---------------------------------------------------------------------------------------------
-- Document location: bytes (0025) or a Storage object (this migration).
-- ---------------------------------------------------------------------------------------------
ALTER TABLE private.membership_documents
  ALTER COLUMN content DROP NOT NULL,
  ADD COLUMN storage_bucket text,
  ADD COLUMN storage_key text;

ALTER TABLE private.membership_documents
  ADD CONSTRAINT membership_document_location CHECK (
    (content IS NOT NULL AND storage_bucket IS NULL AND storage_key IS NULL)
    OR (content IS NULL AND storage_bucket IS NOT NULL AND storage_key IS NOT NULL)),
  ADD CONSTRAINT membership_document_bucket_shape CHECK (
    storage_bucket IS NULL OR storage_bucket ~ '^[A-Za-z0-9][A-Za-z0-9._-]{0,62}$'),
  -- Keys are generated by Core: a fixed prefix, a random UUID and the extension of the type the
  -- file's own bytes established. They carry no name, email or student ID.
  ADD CONSTRAINT membership_document_key_shape CHECK (
    storage_key IS NULL OR storage_key ~
      '^membership-id-cards/[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}\.(jpg|png|webp|pdf)$'),
  ADD CONSTRAINT membership_document_key_type CHECK (
    storage_key IS NULL OR storage_key LIKE ('%.' || (CASE media_type
      WHEN 'image/jpeg' THEN 'jpg' WHEN 'image/png' THEN 'png'
      WHEN 'image/webp' THEN 'webp' WHEN 'application/pdf' THEN 'pdf' END)));

CREATE UNIQUE INDEX membership_documents_storage_object_unique
  ON private.membership_documents (storage_bucket, storage_key) WHERE storage_key IS NOT NULL;

-- ---------------------------------------------------------------------------------------------
-- Objects waiting to be deleted from Storage.
-- ---------------------------------------------------------------------------------------------
CREATE TABLE private.membership_storage_deletions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  storage_bucket text NOT NULL,
  storage_key text NOT NULL,
  -- document_removed: the application was decided (or removed) in the same transaction.
  -- upload_abandoned: an upload failed or its application was refused, so nothing references it.
  reason text NOT NULL CHECK (reason IN ('document_removed', 'upload_abandoned')),
  requested_at timestamptz NOT NULL DEFAULT now(),
  attempts integer NOT NULL DEFAULT 0 CHECK (attempts >= 0),
  last_attempt_at timestamptz,
  completed_at timestamptz,
  CONSTRAINT membership_storage_deletion_bucket_shape CHECK (
    storage_bucket ~ '^[A-Za-z0-9][A-Za-z0-9._-]{0,62}$'),
  CONSTRAINT membership_storage_deletion_key_shape CHECK (storage_key ~
    '^membership-id-cards/[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}\.(jpg|png|webp|pdf)$'),
  CONSTRAINT membership_storage_deletion_object_unique UNIQUE (storage_bucket, storage_key)
);
CREATE INDEX membership_storage_deletions_pending_idx
  ON private.membership_storage_deletions (requested_at) WHERE completed_at IS NULL;

ALTER TABLE private.membership_storage_deletions OWNER TO uc02_routine_owner;
ALTER TABLE private.membership_storage_deletions ENABLE ROW LEVEL SECURITY;
ALTER TABLE private.membership_storage_deletions FORCE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE private.membership_storage_deletions
  FROM PUBLIC, anon, authenticated, service_role, app_runtime, app_maintenance;
CREATE POLICY routine_owner_full_access ON private.membership_storage_deletions
  FOR ALL TO uc02_routine_owner USING (true) WITH CHECK (true);

-- Whatever removes a Storage-backed document row (the decision routine, or a cascade) queues the
-- object in the same transaction, so a committed decision can never leave an untracked object.
CREATE FUNCTION private.queue_removed_membership_document()
RETURNS trigger LANGUAGE plpgsql SET search_path = public, pg_temp AS $$
BEGIN
  IF OLD.storage_key IS NOT NULL THEN
    INSERT INTO private.membership_storage_deletions (storage_bucket, storage_key, reason)
    VALUES (OLD.storage_bucket, OLD.storage_key, 'document_removed')
    ON CONFLICT (storage_bucket, storage_key) DO NOTHING;
  END IF;
  RETURN OLD;
END;
$$;
CREATE TRIGGER membership_document_removed
  AFTER DELETE ON private.membership_documents
  FOR EACH ROW EXECUTE FUNCTION private.queue_removed_membership_document();

